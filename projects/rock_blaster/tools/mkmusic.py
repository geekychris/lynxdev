#!/usr/bin/env python3
"""Rock Blaster: the original's MOD (tools/rock_blaster.mod, "rock storm")
-> src/music.c: two Mikey channels (the Lynx port plays them on 2 and 3).

The MOD's lead and bass channels (the two the Spectrum port's AY plays) are
read row by row in song order; each note lasts until the next note on its
channel. Amiga periods are turned into MIDI notes (period 428 = C-2 in
ProTracker = MIDI 60 here); both fit the SDK's notes (MIDI 48 up).
Speed = ticks a row (50 Hz).
Run: python3 tools/mkmusic.py [--show]
"""
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
d = (HERE / "tools" / "rock_blaster.mod").read_bytes()
songlen = d[950]
order = list(d[952:952 + songlen])
npat = max(d[952:952 + 128]) + 1


def cell(p, row, ch):
    o = 1084 + p * 1024 + row * 16 + ch * 4
    b = d[o:o + 4]
    inst = (b[0] & 0xF0) | (b[2] >> 4)
    period = ((b[0] & 0x0F) << 8) | b[1]
    eff, arg = b[2] & 0x0F, b[3]
    return inst, period, eff, arg


def midi(period):
    return round(60 + 12 * math.log2(428 / period))


speed = 6
rows = []                        # (ticks, [note or None per channel])
for p in order:
    for r in range(64):
        cells = [cell(p, r, c) for c in range(4)]
        for inst, per, eff, arg in cells:
            if eff == 0xF and 0 < arg < 32:
                speed = arg
        rows.append((speed, [midi(per) if per else None for _, per, _, _ in cells],
                     [inst for inst, *_ in cells]))

if "--show" in sys.argv:
    for ch in range(4):
        notes = [n[ch] for _, n, _ in rows if n[ch] is not None]
        insts = sorted({i[ch] for _, _, i in rows if i[ch]})
        print(ch, len(notes), "notes", min(notes, default=0), max(notes, default=0), "instruments", insts)
    sys.exit()

# the lead (channel 0, instrument 1) and the bass (channel 1, instrument 2):
# the two the Spectrum port plays. Channel 2 is drums (one pitch, three
# samples), channel 3 a counter-melody; --show lists them.
lead, bass = 0, 1

def track(ch):
    out = []
    cur, length = 0, 0
    for ticks, n, _ in rows:
        if n[ch] is not None:
            if length:
                out.append((cur, length))
            cur, length = n[ch], 0
        length += ticks
    out.append((cur, length))
    if out[0][0] == 0 and out[0][1] == 0:
        out = out[1:]
    res = []
    for note, ln in out:                   # the length is a byte
        while ln > 255:
            res.append((note, 255))
            ln -= 255
        res.append((note, ln))
    return res


def mikey(note):
    """Mikey timer for a square wave of MIDI `note`: (backup, clock select).
    Output frequency = 1 MHz / 2^sel / (2 * (backup + 1))."""
    hz = 440 * 2 ** ((note - 69) / 12)
    for sel in range(7):
        half = round(1_000_000 / (1 << sel) / (2 * hz))
        if half <= 256:
            return half - 1, sel
    raise ValueError(note)


lt, bt = track(lead), track(bass)
assert sum(l for _, l in lt) == sum(l for _, l in bt)
notes = sorted({n for n, _ in lt + bt if n})
lo, hi = notes[0], notes[-1]
lines = ["/* generated by tools/mkmusic.py from tools/rock_blaster.mod - do not edit */",
         '#include "music.h"', ""]
lines.append(f"/* Mikey timer per MIDI note {lo}..{hi}: backup value, clock select */")
lines.append(f"const uint8_t note_bkup[{hi - lo + 1}] = {{ " + ", ".join(str(mikey(n)[0]) for n in range(lo, hi + 1)) + " };")
lines.append(f"const uint8_t note_sel[{hi - lo + 1}] = {{ " + ", ".join(str(mikey(n)[1]) for n in range(lo, hi + 1)) + " };")
lines.append("")
for name, t in (("music_lead", lt), ("music_bass", bt)):
    lines.append(f"/* {{note - NOTE_LO + 1 (0 = rest), length in 50 Hz ticks}} */")
    lines.append(f"const uint8_t {name}[{2 * len(t) + 2}] = {{")
    for i in range(0, len(t), 10):
        lines.append("    " + ", ".join(f"{(n - lo + 1) if n else 0},{l}" for n, l in t[i:i + 10]) + ",")
    lines.append("    0, 0\n};")
(HERE / "src" / "music.c").write_text("\n".join(lines) + "\n")
(HERE / "src" / "music.h").write_text(
    "/* generated by tools/mkmusic.py - do not edit */\n#ifndef MUSIC_H\n#define MUSIC_H\n#include <stdint.h>\n"
    f"#define NOTE_LO {lo}\n"
    f"extern const uint8_t note_bkup[{hi - lo + 1}], note_sel[{hi - lo + 1}];\n"
    f"extern const uint8_t music_lead[{2 * len(lt) + 2}], music_bass[{2 * len(bt) + 2}];\n#endif\n")
print(f"lead ch{lead}: {len(lt)} notes, bass ch{bass}: {len(bt)} notes, {sum(l for _, l in lt)} frames, MIDI {lo}..{hi}")
